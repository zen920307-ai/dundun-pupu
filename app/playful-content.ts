// A shuffled deck: every item gets a turn before the deck is refilled.
export function shuffledDeck(size: number, initial = -1) {
  let remaining: number[] = [];
  let previous = initial;
  return () => {
    if (!remaining.length) {
      remaining = Array.from({ length: size }, (_, i) => i);
      for (let i = size - 1; i > 0; i--) {
        const j = Math.floor(Math.random() * (i + 1));
        [remaining[i], remaining[j]] = [remaining[j], remaining[i]];
      }
      if (size > 1 && remaining[size - 1] === previous)
        [remaining[0], remaining[size - 1]] = [
          remaining[size - 1],
          remaining[0],
        ];
    }
    previous = remaining.pop()!;
    return previous;
  };
}

// A round can cross a deck boundary; keep its questions distinct too.
export function drawRound(draw: () => number, count: number) {
  const round = new Set<number>();
  while (round.size < count) round.add(draw());
  return [...round];
}

